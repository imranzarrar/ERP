#!/usr/bin/env node
// Builds the test-case catalogue from docs/test-cases/catalogue-source.mjs:
//   docs/test-cases/test-case-catalogue.csv   (UTF-8 with BOM: opens in Excel; imports into TestRail / Xray / Zephyr / Azure Test Plans)
//   docs/test-cases/test-case-catalogue.json  (for scripts and test runners)
//   docs/test-cases/features/<module>.feature (Gherkin for Cucumber / Playwright-BDD / Behave: one Feature per module, one Scenario per case)
//   docs/test-cases/README.md                 (coverage matrix and how to automate)
// It also checks that every "tests/....test.ts" a case claims as its automation really exists, so the catalogue cannot promise coverage that is not there.
// Usage: node scripts/build-test-catalogue.mjs [--check]   (--check only validates, writes nothing)
import fs from 'node:fs';
import path from 'node:path';
import { MODULES, CASES } from '../docs/test-cases/catalogue-source.mjs';

const OUT = 'docs/test-cases';
const CHECK = process.argv.includes('--check');
const problems = [];
const seen = new Set();
for (const c of CASES) {
  if (seen.has(c.id)) problems.push(`duplicate id ${c.id}`); seen.add(c.id);
  if (!['Functional', 'Negative', 'Boundary', 'Security', 'Integration', 'Regression', 'Usability', 'Performance'].includes(c.type)) problems.push(`${c.id}: unknown type ${c.type}`);
  if (!['P1', 'P2', 'P3'].includes(c.priority)) problems.push(`${c.id}: unknown priority ${c.priority}`);
  if (!['API', 'DB', 'UI', 'API+DB', 'UI+API'].includes(c.layer)) problems.push(`${c.id}: unknown layer ${c.layer}`);
  if (c.automation.startsWith('tests/')) { if (!fs.existsSync(c.automation)) problems.push(`${c.id}: automation file ${c.automation} does not exist`); }
  else if (!['Candidate', 'Manual'].includes(c.automation)) problems.push(`${c.id}: automation must be a tests/ file, Candidate or Manual`);
  for (const k of ['title', 'given', 'when', 'then']) if (!String(c[k] || '').trim()) problems.push(`${c.id}: empty ${k}`);
}
if (problems.length) { console.error('Catalogue problems:\n  ' + problems.join('\n  ')); process.exit(1); }
const status = (c) => (c.automation.startsWith('tests/') ? 'Automated' : c.automation);
if (CHECK) { console.log(`Catalogue OK: ${CASES.length} cases in ${MODULES.length} modules.`); process.exit(0); }

fs.mkdirSync(path.join(OUT, 'features'), { recursive: true });

// ---- CSV ----
const q = (v) => `"${String(v).replace(/"/g, '""')}"`;
const head = ['ID', 'Module', 'Title', 'Type', 'Priority', 'Preconditions (Given)', 'Steps (When)', 'Expected result (Then)', 'Layer', 'Automation status', 'Automated by', 'Reference'];
const rows = CASES.map(c => [c.id, c.module, c.title, c.type, c.priority, c.given, c.when, c.then, c.layer, status(c), c.automation.startsWith('tests/') ? c.automation : '', c.ref]);
fs.writeFileSync(path.join(OUT, 'test-case-catalogue.csv'), '﻿' + [head, ...rows].map(r => r.map(q).join(',')).join('\r\n') + '\r\n');

// ---- JSON ----
fs.writeFileSync(path.join(OUT, 'test-case-catalogue.json'), JSON.stringify({ generated: new Date().toISOString().slice(0, 10), modules: MODULES, cases: CASES.map(c => ({ ...c, status: status(c) })) }, null, 2));

// ---- Gherkin ----
const tag = (s) => s.replace(/[^A-Za-z0-9+]/g, '');
for (const m of MODULES) {
  const cs = CASES.filter(c => c.moduleId === m.id); if (!cs.length) continue;
  const lines = [`# Generated by scripts/build-test-catalogue.mjs from docs/test-cases/catalogue-source.mjs. Do not edit.`, `@${m.id}`, `Feature: ${m.name}`, `  Reference: ${m.ref}`, ''];
  for (const c of cs) {
    lines.push(`  @${c.id} @${c.priority} @${tag(c.type)} @${tag(c.layer)} @${status(c).toLowerCase()}`);
    lines.push(`  Scenario: ${c.title}`);
    lines.push(`    Given ${c.given}`);
    lines.push(`    When ${c.when}`);
    lines.push(`    Then ${c.then}`);
    if (c.automation.startsWith('tests/')) lines.push(`    # automated by ${c.automation}`);
    lines.push('');
  }
  fs.writeFileSync(path.join(OUT, 'features', `${m.id.toLowerCase()}.feature`), lines.join('\n'));
}

// ---- README ----
const count = (f) => CASES.filter(f).length;
const matrix = MODULES.map(m => {
  const cs = CASES.filter(c => c.moduleId === m.id);
  return `| ${m.id} | ${m.name} | ${cs.length} | ${cs.filter(c => c.priority === 'P1').length} | ${cs.filter(c => status(c) === 'Automated').length} | ${cs.filter(c => c.automation === 'Candidate').length} | ${cs.filter(c => c.automation === 'Manual').length} |`;
}).join('\n');
const readme = `# Test-case catalogue (generated)

**${CASES.length} cases** across ${MODULES.length} modules, written so a tool can run them. Generated from \`catalogue-source.mjs\` by \`node scripts/build-test-catalogue.mjs\`; edit the source, never these files.

| Files | Use |
|---|---|
| \`test-case-catalogue.csv\` | Excel, TestRail, Jira Xray / Zephyr, Azure Test Plans (UTF-8 with BOM; one row per case, Given / When / Then in separate columns) |
| \`test-case-catalogue.json\` | scripts, dashboards, custom runners |
| \`features/*.feature\` | Gherkin, one Feature per module: Cucumber, Playwright-BDD, Behave, SpecFlow. Tags carry priority, type, layer and automation status (\`@P1 @Negative @API @automated\`) |

## Coverage today

| Module | Name | Cases | P1 | Already automated | Candidate | Manual |
|---|---|---|---|---|---|---|
${matrix}
| | **Total** | **${CASES.length}** | **${count(c => c.priority === 'P1')}** | **${count(c => status(c) === 'Automated')}** | **${count(c => c.automation === 'Candidate')}** | **${count(c => c.automation === 'Manual')}** |

* **Automated**: mapped to the existing vitest file in \`tests/\` that exercises it, against a real server and real Postgres (no mocks). \`--check\` fails if the named file does not exist. The mapping is by area, so read it as "covered by that file", not "every Then clause is asserted": when you tighten a case or automate a Candidate, put its ID in the \`it(...)\` title so a run traces back to the catalogue.
* **Candidate**: can be automated exactly as written, as an API test (same style as \`tests/settlements.test.ts\`) or a DB assertion.
* **Manual**: needs eyes (print layout, right-to-left look, drag-and-drop feel) or a human decision. Browser automation (Playwright) can cover most of them once a stable test company exists.

## How to automate with a tool

1. **API and DB scenarios (the large majority)**: they already run under vitest. To add a Candidate, copy the nearest existing test file, give the case ID in the \`it('...')\` title (\`it('RCP-021 ...')\`) and flip its \`automation\` field in the source to the file path.
2. **UI scenarios**: use Playwright. Log in through the UI with a throw-away company created by the same fixture helpers the vitest files use (\`mkCompany\`), drive the real screens, and assert on the same figures the API tests assert. The \`.feature\` files map one-to-one to Playwright-BDD scenarios.
3. **Load scenarios (module NFR)**: k6 or Artillery against \`/api/login\`, dashboard, invoice and receipt creation with the thresholds written in the case.
4. **Importing to a test-management tool**: import the CSV; the columns map to Title, Priority, Preconditions, Steps, Expected result, Automation status.

## Ground rules the cases assume

* Every scenario runs in its own throw-away company (fixture + purge in \`afterAll\`), never in a seeded demo company.
* Real HTTP against a running server plus direct Postgres assertions. No mocks.
* Test through the real screens or routes a user can reach; API-only data that no user could create is not a valid fixture.
`;
fs.writeFileSync(path.join(OUT, 'README.md'), readme);
console.log(`Catalogue written: ${CASES.length} cases, ${MODULES.length} modules, ${count(c => status(c) === 'Automated')} already automated, ${count(c => c.automation === 'Candidate')} candidates, ${count(c => c.automation === 'Manual')} manual.`);
